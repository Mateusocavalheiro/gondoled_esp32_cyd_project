Adafruit_ST7789 tft = Adafruit_ST7789(TFT_CS, TFT_DC, TFT_MOSI, TFT_CLK, TFT_RST);

void UI_Init() {
    pinMode(TFT_BL, OUTPUT);
    digitalWrite(TFT_BL, HIGH);
    tft.init(240, 320);
    tft.invertDisplay(0); 
    // 0 = Retrato, 1 = Paisagem, 2 = Retrato Invertido, 3 = Paisagem Invertida
    tft.setRotation(1);
    // --- CÓDIGO TEMPORÁRIO DE TESTE DE CALIBRAÇÃO ---
    tft.fillScreen(0x0000); // Pinta de preto para o branc destacar bem
    tft.drawRect(0, 0, 320, 240, 0xFFFF); // Borda branc
    tft.drawLine(0, 0, 320, 240, 0xFFFF); // X cruzado
    tft.drawLine(320, 0, 0, 240, 0xFFFF);
}

String formatarPrecoReal(float preco) {
    char buf[15];
    sprintf(buf, "R$ %.2f", preco);
    String str = String(buf);
    str.replace(".", ",");
    return str;
}

